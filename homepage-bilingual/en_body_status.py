def body_status(i):
    """回傳 (狀態, 剩餘中文比例, 建立方式, 建議做法, 優先)；不在清單回傳 None"""
    if i not in RAW: return None
    n, u, ec, el, zc, raw, txt, row, woo = RAW[i]
    pct = (ec / zc) if zc else 0
    if raw and txt: build = 'WPBakery（Raw HTML＋Text Block 混合）'
    elif raw: build = 'WPBakery Raw HTML'
    elif txt: build = 'WPBakery Text Block'
    elif woo and not row: build = 'WooCommerce 頁'
    else: build = '非 WPBakery（傳統／區塊編輯器）'
    if i in SKIP:
        return ('不需要', f'{pct:.0%}', build, SKIP[i], '—')
    if pct <= 0.05: st = '已翻譯'
    elif pct <= 0.2: st = '大致已翻譯（餘少量中文）'
    elif pct <= 0.6: st = '部分翻譯'
    else: st = '未翻譯（英文版只有中文）'
    if i in SMALL and st.startswith('未'): st = '未翻譯（內容很少）'
    if st == '已翻譯': how = '—'
    elif st.startswith('大致') or (i in SMALL):
        how = '用 TranslatePress 翻譯編輯器補餘下字句'
    elif build.startswith('WPBakery'):
        how = '複製該元件：原有元件 Extra class 加 ao-zh；新元件貼英文 HTML，Extra class 加 ao-en'
    else:
        how = '原有內容用 [ao_zh]…[/ao_zh] 包住，下面加 [ao_en]英文 HTML[/ao_en]'
    if i == 17: how = 'Raw HTML 及 Text Block 逐個元件加 ao-zh／ao-en（已有部分英文）'
    if i == 7014: how = '用 TranslatePress 補餘下中文（多為產品名及按鈕）'
    return (st, f'{pct:.0%}', build, how, PRIORITY.get(i, '—' if st == '已翻譯' else 'P3'))
